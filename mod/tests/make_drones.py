"""Image 31: the ten DigiDrone sounds as stored sounds, made by the emulated OS itself. Each is set up on an FM TONE
track (every slot of experiments/b29_patches.py / b30_patches.py), named, and saved with stock's converter
(0x400dd6a6, live sound -> stored sound, as make_brickglide_pad.py). Checked: loaded into another track with stock's
loader (0x400dd1ea) it is FM TONE, has its name and every slot.
Writes ~/glide/sounds/b31/NAME.stored.bin and mod/dg_drones.h (the blobs and each sound's DigiGlide settings).
    ~/dn2-workspace/repos/digikit/.venv/bin/python make_drones.py DIGIGLIDE.syx
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.expanduser('~/glide/experiments'))
from dgkit import Session, latest
from osver import A
import cfkit
import b29_sounds, b29_patches, b30_patches
import b33_patches                                   # image 33: the deep set replaces the first ten's values

img = sys.argv[1] if len(sys.argv) > 1 else latest()
OUT = os.path.expanduser('~/glide/sounds/b31')
ok = True


def check(c, msg):
    global ok
    ok &= bool(c)
    print(('  ok   ' if c else '  FAIL ') + msg, flush=True)


from make_drones_tab import ORDER

# LFO1 (sound slots 1..8: SPD MULT FADE DEST WAVE SPH MODE DEP). From the firmware's own value texts (build log,
# image 25): SPD (v - 0x4000) / 256, MULT index 0 = x1, DEST = the sound slot, DEP (v - 0x4000) / 128. SPD x MULT =
# 16 is 8 bars, 8 is 16 bars. test_b31_drones D sees the stock LFO move DARK RING's filter at that rate.
def lfo(lf):
    if not lf:
        return {1: 0x7000, 2: 0x100, 4: 0, 8: 0x4000}    # the defaults (no destination)
    row, centre, depth, bars = lf
    dest = b29_sounds.S.Sound('FMTONE').names[row.upper()]
    return {1: 0x4000 + (128 // bars) * 256, 2: 0, 4: dest << 8, 8: 0x4000 + depth // 2}    # measured (test_b31_drones D): the swing is 2 x (DEP word - 0x4000)


s = Session(img, tag='drones')
k, h = s.k, s.k.h
if k.mach(0) != 0:
    k.select(0, track=0)
check(k.mach(0) == 0, f'track 1 is FM TONE (machine {k.mach(0)})')
BUF = cfkit.SPARE + 0x10000
blobs, length = [], 0
for name, dgs in ORDER:
    title, text, knobs, couple, lf, _, cap = b29_sounds.SOUNDS[name]
    snd = b29_sounds.sound(name)
    slots = dict(snd.slots)
    for r in b29_sounds.S.PARAM_ROWS:                # LFO1..3 at their defaults: no destination (the demo sound this is
        if r['grp'] in (26, 27, 28):                 # built on has an LFO on slot 25, FM TONE's ALGO)
            slots.setdefault(r['id'], r['dflt'])
    slots.update(lfo(lf))
    for sid, v in slots.items():
        k.sound_slot(0, sid, v)
    h.w(k.sound(0) + 4, title.encode().ljust(16, b'\0'))
    h.w(BUF, bytes([0xA5]) * 0x800)
    r = k.call(A(0x400DD6A6), [BUF, k.sound(0), 0])
    raw = bytes(h.r(BUF, 0x800))
    n = max(i for i in range(0x800) if raw[i] != 0xA5) + 1
    length = max(length, n)
    # load it into track 6 and compare
    h.w(k.sound(5) + 4, bytes(16))
    r2 = k.call(A(0x400DD1EA), [k.sound(5), BUF])
    nm = bytes(h.r(k.sound(5) + 4, 16)).split(b'\0')[0].decode()
    bad = {sid: (hex(v), hex(k.sound_slot(5, sid))) for sid, v in slots.items() if k.sound_slot(5, sid) != v}
    check(r & 0xFF and r2 & 0xFF and raw[:4] == bytes.fromhex('beefbace') and k.mach(5) == 0 and nm == title and not bad,
          f'{title}: saved ({n} bytes), loaded into track 6: FM TONE, "{nm}", {len(slots)} slots equal {bad or ""}')
    blobs.append((name, title, raw, dgs))
length = (length + 3) & ~3
check(length <= 0x400, f'stored sounds are at most {length} bytes')
L = ['/* generated by tests/make_drones.py: the ten DigiDrone sounds as stock stored sounds (the OS\'s own converter',
     ' * wrote them in the emulator), and the DigiGlide settings each one sets: pairs of (K_ index, value), 255 ends. */',
     f'#define DRONE_N {len(blobs)}', f'#define DRONE_LEN {length}',
     'static const char *const DRONE_NAME[DRONE_N] = {' + ', '.join(f'"{t}"' for _, t, _, _ in blobs) + '};',
     'static const uint8_t DRONE_DG[DRONE_N][30] = {']
for name, title, raw, dgs in blobs:
    L.append('    {' + ', '.join(f'{a}, {b}' for a, b in dgs) + ', 255, 255},')
L.append('};')
L.append('static const uint8_t DRONE_SND[DRONE_N][DRONE_LEN] = {')
for name, title, raw, dgs in blobs:
    open(f'{OUT}/{name}.stored.bin', 'wb').write(raw[:length])
    L.append('    {' + ','.join(str(b) for b in raw[:length]) + '},')
L.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'dg_drones.h'), 'w').write('\n'.join(L) + '\n')
print('OK' if ok else 'FAIL')
sys.exit(0 if ok else 1)
