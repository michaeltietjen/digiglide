"""Build the M2 self-test image (core + dg_selftest.c, no hooks) for the ColdFire emulator, and check the build:
no libgcc helper linked (this toolchain's libgcc is 68020 code), no float, sizes.
    python3 build_selftest.py [seeds...]      (default seeds 1 2 3 4)
-> $DN2_WORKSPACE/build/DG_SELFTEST.syx (+ DG_SELFTEST/section_3.bin, symbols.txt) and selftest_events.h"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.expanduser('~/glide/.claude/skills/digitone-2-modding-skill/scripts'))
import cfmod, dn2paths as P
import test_equiv as T

OURS = {'__bss_start', '__bss_end', '__image_end'}


def events_header(seeds, max_blocks=6000):
    cases, rows = [], []
    for s in seeds:
        tw, pat, ev, nb = T.case(s)
        nb = min(nb, max_blocks)
        ev = [e for e in ev if e[0] < nb]
        cases.append((tw, pat, len(rows), len(ev), nb))
        for b, kind, step, val, p in ev:
            rows.append([b, kind, step, val] + ([p[f] for f in T.FIELDS] if p else [0] * 16))
    out = ['/* generated by build_selftest.py from test_equiv.case(seed) */',
           f'/* seeds {seeds}: tempo word, pattern, first event, events, blocks */',
           f'static const int32_t ST_CASES[{len(cases)}][5] = {{']
    out += ['  {%s},' % ', '.join(map(str, c)) for c in cases] + ['};', f'static const int32_t ST_EV[{len(rows)}][20] = {{']
    out += ['  {%s},' % ', '.join(map(str, r)) for r in rows] + ['};']
    open(os.path.join(HERE, 'selftest_events.h'), 'w').write('\n'.join(out) + '\n')
    return cases


def check_symbols(symfile):
    bad = []
    for line in open(symfile):
        parts = line.split()
        if parts and parts[-1].startswith('__') and parts[-1] not in OURS:
            bad.append(parts[-1])
    return bad


if __name__ == '__main__':
    seeds = [int(a) for a in sys.argv[1:]] or [1, 2, 3, 4]
    cases = events_header(seeds)
    out = str(P.BUILD / 'DG_SELFTEST.syx')
    m = cfmod.Mod([os.path.join(HERE, f) for f in ('dg_core.c', 'dg_selftest.c')],
                  entries=['dg_selftest_start', 'dg_selftest_run', 'st_hash', 'st_b'], init='dg_selftest_init',
                  include=[HERE])
    m.write(out)
    sym = str(P.BUILD / 'DG_SELFTEST' / 'symbols.txt')
    bad = check_symbols(sym)
    print(out)
    print('libgcc / runtime helpers linked:', bad or 'none')
    sys.exit(1 if bad else 0)
