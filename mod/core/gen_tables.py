"""Generate dg_tables.h: lookup tables for the DigiGlide C core (no FPU on the ColdFire).
    python3 gen_tables.py > dg_tables.h
DG_SIN: sin over one cycle, 2048 steps + guard, Q29.  DG_SMOOTH: Brickglide's Smooth shape over p = 0..1, 2048 steps
+ guard, Q29. Both are read with linear interpolation."""
import math
N = 2048
Q = 1 << 29
def q(x):
    return int(math.floor(x * Q + 0.5))
sinv = [q(math.sin(2 * math.pi * k / N)) for k in range(N + 1)]
smooth = [q((1 - math.exp(-5 * k / N)) / (1 - math.exp(-5))) for k in range(N + 1)]
out = ['/* generated by gen_tables.py: do not edit */', '#ifndef DG_TABLES_H', '#define DG_TABLES_H',
       '#define DG_TAB_BITS 11']
for name, t in (('DG_SIN', sinv), ('DG_SMOOTH', smooth)):
    out.append(f'static const int32_t {name}[{N + 1}] = {{')
    for k in range(0, len(t), 8):
        out.append('  ' + ', '.join(str(v) for v in t[k:k + 8]) + ',')
    out.append('};')
out.append('#endif')
print('\n'.join(out))
